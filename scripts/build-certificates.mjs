// Regenerates the certificate cards in index.html from data/certificates.json.
//   node scripts/build-certificates.mjs
// Add a certificate = add its images to assets/certificates/ + one object in the JSON, then run this.
import { readFileSync, writeFileSync } from 'node:fs';

const root = new URL('../', import.meta.url);
const data = JSON.parse(readFileSync(new URL('data/certificates.json', root), 'utf8'));
const esc = (s) => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
const label = Object.fromEntries(data.categories.map((c) => [c.id, c.label]));

const filters = [
  `<button type="button" class="cert-filter" data-filter="all" aria-pressed="true">All <span class="cert-filter-n">${data.certificates.length}</span></button>`,
  ...data.categories
    .map((c) => ({ c, n: data.certificates.filter((x) => x.category === c.id).length }))
    .filter(({ n }) => n > 0)
    .map(({ c, n }) => `<button type="button" class="cert-filter" data-filter="${esc(c.id)}" aria-pressed="false">${esc(c.label)} <span class="cert-filter-n">${n}</span></button>`),
].join('\n          ');

const cards = data.certificates
  .map((c) => {
    const verify = c.verifyUrl
      ? `\n          <a class="cert-verify" href="${esc(c.verifyUrl)}" target="_blank" rel="noopener noreferrer">Verify<span class="sr-only"> ${esc(c.title)} (opens in a new tab)</span></a>`
      : '';
    return `        <li class="cert-item" data-category="${esc(c.category)}">
          <button type="button" class="cert-tile" aria-haspopup="dialog"
            data-full="${esc(c.image)}" data-w="${c.imageSize[0]}" data-h="${c.imageSize[1]}"
            data-title="${esc(c.title)}" data-issuer="${esc(c.issuer)}" data-date="${esc(c.date || '')}"
            data-type="${esc(c.type)}" data-alt="${esc(c.alt)}">
            <span class="cert-thumb"><img src="${esc(c.thumb)}" alt="" width="${c.thumbSize[0]}" height="${c.thumbSize[1]}" loading="lazy" decoding="async" /></span>
            <span class="cert-body">
              <span class="cert-cat">${esc(label[c.category] || c.category)}</span>
              <span class="cert-title">${esc(c.title)}</span>
              <span class="cert-issuer">${esc(c.issuer)}</span>
              ${c.date ? `<span class="cert-date">${esc(c.date)}</span>` : ''}
              <span class="cert-view">View certificate <span aria-hidden="true">→</span></span>
            </span>
          </button>${verify}
        </li>`;
  })
  .join('\n');

const block = `<!-- CERTS:START (generated by scripts/build-certificates.mjs from data/certificates.json — edit the JSON, not this block) -->
        <div class="cert-filters" role="group" aria-label="Filter certificates by category">
          ${filters}
        </div>
        <ul class="cert-grid" id="cert-grid">
${cards}
        </ul>
        <!-- CERTS:END -->`;

const file = new URL('index.html', root);
let html = readFileSync(file, 'utf8');
const re = /<!-- CERTS:START[\s\S]*?<!-- CERTS:END -->/;
if (!re.test(html)) throw new Error('CERTS markers not found in index.html');
writeFileSync(file, html.replace(re, () => block));
console.log(`Rendered ${data.certificates.length} certificates.`);
